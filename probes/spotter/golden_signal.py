"""Golden fixtures for crates/max-wake spectrum, fbank and freqfilter tests.

usage: /tmp/litert-venv/bin/python -I golden_signal.py [out_dir]   (default crates/max-wake/tests/fixtures)

Inputs are integer LCG noise, optionally run through f64 biquads whose coefficients go into the
fixture, so the Rust tests rebuild them bit-exactly. Expected values come from proto.py
(Frontend), freqfilter.py and gate.py.
"""
import math
import pathlib
import sys

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import freqfilter  # noqa: E402
import gate  # noqa: E402
from proto import FRAME, SHIFT, Frontend  # noqa: E402

FBANK_SAMPLES = 2400
FF_SAMPLES = 56000
FF_CHUNK = 2000
RATE = 16000


def lcg(seed, n):
    x, out = seed, []
    for _ in range(n):
        x = (x * 1664525 + 1013904223) & 0xFFFFFFFF
        out.append((x >> 16) - 32768)
    return out


def fbank_input():
    a, b = lcg(1, FBANK_SAMPLES), lcg(2, FBANK_SAMPLES)
    omni = [(a[i] >> 3) + ((i * 7) % 160) * 50 - 4000 for i in range(FBANK_SAMPLES)]
    bnr = [(b[i] >> 4) + (2000 if (i // 40) % 2 else -2000) for i in range(FBANK_SAMPLES)]
    for i in range(1600, 2000):
        omni[i] = 0
        bnr[i] = 0
    return np.array(omni, dtype=np.int16), np.array(bnr, dtype=np.int16)


def biquads(gain_ratio):
    """One resonator per filter frequency: zeros at radius rz, poles at rp, gain ~ (1-rz)/(1-rp)."""
    rp = 0.99
    rz = 1 - gain_ratio * (1 - rp)
    out = []
    for f in freqfilter.FREQS_HZ:
        c = math.cos(2 * math.pi * f / RATE)
        out.append((1.0, -2 * rz * c, rz * rz, -2 * rp * c, rp * rp))
    return out


def ff_input(stages):
    s = [u / 16 for u in lcg(3, FF_SAMPLES)]
    for b0, b1, b2, a1, a2 in stages:
        x1 = x2 = y1 = y2 = 0.0
        for i, x in enumerate(s):
            y = b0 * x + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2
            x2, x1, y2, y1 = x1, x, y1, y
            s[i] = y
    return np.array([min(32767, max(-32768, round(v))) for v in s], dtype=np.int16)


def f32(v):
    return str(np.float32(v))


def main():
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent.parent / "crates/max-wake/tests/fixtures"
    out.mkdir(parents=True, exist_ok=True)

    np.random.RandomState(42).randn(2048).astype("<f4").tofile(out / "dither42.f32le")

    omni, bnr = fbank_input()
    fe = Frontend()
    feats = []
    for start in range(0, FBANK_SAMPLES - FRAME + 1, SHIFT):
        feats.append(np.concatenate([fe.frame(omni[start:start + FRAME]), fe.frame(bnr[start:start + FRAME])]))
    np.array(feats, dtype="<f4").tofile(out / "fbank.f32le")

    cases = {"noise": [], "notched": biquads(0.1), "boosted": biquads(4.0)}
    lines = ["# generated by probes/spotter/golden_signal.py from freqfilter.py and gate.py"]
    for name, stages in cases.items():
        for st in stages:
            lines.append(f"biquad {name} " + " ".join(repr(v) for v in st))
    for name, stages in cases.items():
        pcm = ff_input(stages)
        ff = freqfilter.FreqFilter()
        ffeats, ends = ff.process(pcm)
        for j, row in enumerate(ffeats):
            lines.append(f"features {name} {j} " + " ".join(f32(v) for v in row))
        for pushed in range(FF_CHUNK, FF_SAMPLES + 1, FF_CHUNK):
            n = int(np.count_nonzero(ends <= pushed))
            now = pushed // gate.SPOT_HOP
            for hit in (now, now - 25, now - 100, now - 250, now - 330):
                if hit < 0:
                    continue
                r = gate.gate_detailed(ffeats[:n], hit)
                value = "none" if r["value"] is None or r["count"] == 0 else f32(r["value"])
                lines.append(f"gate {name} {pushed} {hit} {value}")
        sums = ffeats.sum(axis=1)
        print(f"{name}: frames {len(ends)}, frame sum min {sums.min():+.2f} max {sums.max():+.2f}")
    (out / "freqfilter.txt").write_text("\n".join(lines) + "\n")
    print(f"fbank frames {len(feats)}; fixtures in {out}")


if __name__ == "__main__":
    main()
